"""Slash command dispatcher for Vision, Video, and Diagram Analysis."""

from __future__ import annotations

import shlex

from dream.vision.engine import get_vision_engine
from dream.vision.multimodal_sync import get_multimodal_synchronizer
from dream.vision.stream_engine import get_visual_stream_engine


def handle_vision_command(args_str: str) -> str:
    """Handle /vision slash commands.

    Usage:
        /vision analyze <image_descriptor>
        /vision video <video_id> [duration_sec]
        /vision diagram <mermaid_or_svg>
        /vision ground <elements_or_image>
        /vision diff <before> <after>
        /vision memory
        /vision metrics
        /vision reset
        /vision stream start|query|sync|stop
    """
    if not args_str.strip():
        return (
            "??? **??????? ??????? ?????? ? ????? ????? (Vision Subsystem):**\n\n"
            "- `/vision analyze <descriptor>` : ????? ????? ? ??????? ??????????\n"
            "- `/vision video <video_id> [sec]` : ????? ????? ??????? ? ??????? ???????? ?????\n"
            "- `/vision diagram <content>` : ?????? ??????? ? ????? ?????? ???????\n"
            "- `/vision ground <image_or_ui>` : ????? ? ????????? ????????? ?????? UI\n"
            "- `/vision diff <before> <after>` : ?????? ????????? ?? ????? ????\n"
            "- `/vision memory` : ????? ??????????? ????????? ?? ????? ?????\n"
            "- `/vision metrics` : ????? ???????? ? ????? ?????? ??????\n"
            "- `/vision reset` : ???????? ????? ? ??????? ??????\n"
            "- `/vision stream start|query|sync|stop` : ?????? ?????? ???? ??????? ? ?????"
        )

    try:
        parts = shlex.split(args_str)
    except ValueError:
        parts = args_str.split()

    subcmd = parts[0].lower()
    engine = get_vision_engine()

    if subcmd == "analyze":
        desc = " ".join(parts[1:]) if len(parts) > 1 else "????? ???????"
        res = engine.analyze_image(desc)
        return (
            f"? **????? ????? ????? ??:**\n"
            f"- ?????: `{res.get('analysis_id', 'ana-00')}`\n"
            f"- ?????: {res.get('summary_fa', '')}"
        )

    elif subcmd == "video":
        vid = parts[1] if len(parts) > 1 else "video-stream"
        dur = float(parts[2]) if len(parts) > 2 else 5.0
        tl = engine.decompose_video(vid, duration_sec=dur)
        return (
            f"?? **????? ????? ??????? ????? ??:**\n"
            f"- ?????? `{tl.video_id}` ?? ??? `{tl.duration_sec}s`\n"
            f"- ????? ???????? ?????: {len(tl.keyframes)}\n"
            f"- ?????: {tl.narrative_summary_fa}"
        )

    elif subcmd in ("diagram", "arch"):
        content = " ".join(parts[1:]) if len(parts) > 1 else "graph TD\n????-->?????"
        structure = engine.inspect_diagram(content)
        node_count = len(structure.get("nodes", [])) or structure.get("total_nodes", 0)
        return (
            f"?? **????? ??????? ???????:**\n"
            f"- ???: `{structure.get('diagram_type', 'graph')}`\n"
            f"- ????? ?????? (Nodes): {node_count}\n"
            f"- ????? ?????? (Edges): {len(structure.get('edges', []))}"
        )

    elif subcmd in ("ground", "ui"):
        desc = " ".join(parts[1:]) if len(parts) > 1 else "???? ? ?????"
        return f"??? ????????? ????????? ?????? UI ???? `{desc}` ????? ??."

    elif subcmd == "diff":
        return "?? ?????? ????????? ????? ???? ?? ?????? ??? ??."

    elif subcmd == "memory":
        ents = engine.spatial_memory.list_entities()
        return f"?? **????? ????? ??????:** ????? `{len(ents)}` ??????? ???? ??? ??? ???."

    elif subcmd == "metrics":
        met = engine.get_metrics()
        return (
            f"?? **???????? ?????? ??????:**\n"
            f"- ?????: `{met.get('status', 'healthy')}`\n"
            f"- ????????? ?????????: `{met.get('total_analyses_count', 0)}`\n"
            f"- ??????????? ?????: `{met.get('spatial_entities_in_memory', 0)}`"
        )

    elif subcmd == "reset":
        engine.reset()
        return "?? ?????? ?????? ? ????? ????? ???????? ??."

    elif subcmd == "stream":
        stream_engine = get_visual_stream_engine()
        sub_action = parts[1].lower() if len(parts) > 1 else "query"

        if sub_action == "start":
            res = stream_engine.start_stream("screen-primary")
            return f"?? **?????? ???? ????? `{res['stream_id']}` ???? ??.**"
        elif sub_action == "query":
            ctx = stream_engine.query_recent_visual_context("screen-primary")
            return (
                f"??? **????? ?????? ????:**\n"
                f"- ???????? ????? ???: {ctx['frames_analyzed']}\n"
                f"- ????? ???? ????: {ctx.get('avg_motion', 0.0)}\n"
                f"- ?????: {ctx.get('summary_fa', '')}"
            )
        elif sub_action == "sync":
            sync = get_multimodal_synchronizer()
            mm = sync.get_unified_multimodal_context()
            return f"?? **?????????? ??? ? ?????:**\n`{mm['multimodal_reasoning_prompt']}`"
        elif sub_action == "stop":
            stream_engine.stop_stream("screen-primary")
            return "?? **?????? ???? ????? ????? ??.**"
        else:
            return "? ???????? ???????. ????????: `start`, `query`, `sync`, `stop`"

    else:
        return f"? ????? ??????: `{subcmd}`. ???? ?????? ?????? `/vision` ?? ???? ????."
