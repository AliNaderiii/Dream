def is_docstring_node(node, parent_body) -> bool:
    """Check if node is a docstring (first statement in module/class/function)."""
    if parent_body and len(parent_body) > 0:
        first_stmt = parent_body[0]
        if isinstance(first_stmt, ast.Expr) and first_stmt.value is node:
            return True
    return False


def check_persian_escaping_in_file(filepath: str, rel_filename: str) -> list[str]:
    """Inspect one .py file for unescaped Persian string literals not in baseline."""
    with open(filepath, encoding="utf-8") as f:
        content = f.read()
    tree = ast.parse(content, filename=filepath)

    violations = []
    allowed_set = BASELINE_UNESCAPED_HASHES.get(rel_filename, set())

    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            seg = ast.get_source_segment(content, node)
            # Only check literals whose raw UTF-8 source segment contains unescaped Persian
            if seg and any("\u0600" <= c <= "\u06FF" for c in seg):
                h = hashlib.sha256(node.value.encode("utf-8")).hexdigest()[:12]
                if h not in allowed_set:
                    violations.append(
                        f"Unescaped Persian string literal found in dream/{rel_filename} "
                        f"at line {node.lineno}: {node.value!r}. "
                        "New Persian strings in product code must use \\u06xx unicode escapes."
                    )
    return violations


